(* Generate the shared TypeScript keyword tables used by abella_doc and
   Abella Web from the reserved words in Lexer.keywords. *)

open Abella_lib
open Extensions

type category =
  | TopBuilt
  | TopCmd
  | ProofCmd
  | ProofSpec
  | Term
  | Sig
  | Lprolog

(* A new reserved word with an unlisted token fails here, so the
   highlighting categories cannot silently drift from the lexer. *)
let category (name, token) =
  let open Parser in
  match token with
  | CLOSE | IMPORT | QUERY | QUIT | SET | SHOW | SPECIFICATION ->
      TopBuilt
  | CODEFINE | DEFINE | THEOREM | AXIOM | SSPLIT | SUSPEND | KKIND | TTYPE
  | AS | BY ->
      TopCmd
  | ABBREV | ALL | APPLY | ASSERT | BACKCHAIN | CASE | CLEAR | COIND
  | COMPUTE | CUT | FROM | IND | INST | INTROS | KEEP | LEFT
  | MONOTONE | ON | PERMUTE | RENAME | RIGHT | SEARCH | SPLIT
  | SPLITSTAR | SATURATE | TO | UNABBREV | UNFOLD | WITH | WITNESS ->
      ProofCmd
  | ABORT | SKIP | UNDO ->
      ProofSpec
  | EXISTS | FALSE | FORALL | NABLA | TRUE ->
      Term
  | KIND | TYPE ->
      Sig
  | ACCUMSIG | ACCUM | END | MODULE | SIG ->
      Lprolog
  | _ ->
      failwithf "keyword %S has no highlighting category" name

let groups = [
  "topBuilt", TopBuilt ;
  "topCmd", TopCmd ;
  "proofCmd", ProofCmd ;
  "proofSpec", ProofSpec ;
  "term", Term ;
  "sig", Sig ;
  "lprolog", Lprolog ;
]

let check_keywords () =
  let seen = Hashtbl.create 67 in
  List.iter (fun ((name, _) as keyword) ->
      if Hashtbl.mem seen name then failwithf "duplicate keyword %S" name ;
      Hashtbl.add seen name (category keyword))
    Lexer.keywords

let words_of cat =
  Lexer.keywords |>
  List.filter_map (fun ((name, _) as keyword) ->
      if category keyword = cat then Some name else None) |>
  List.sort String.compare

let all_words () =
  List.map fst Lexer.keywords |> List.sort String.compare

let check_groups () =
  let listed =
    List.concat_map (fun (_, cat) -> words_of cat) groups |>
    List.sort String.compare
  in
  if listed <> all_words () then
    failwith "keyword groups do not cover the lexer"

let output path =
  let oc = open_out_bin path in
  Fun.protect ~finally:(fun () -> close_out oc) begin fun () ->
    output_string oc
      "// Generated by bin/abella_keywords.ml from the keyword table in\n\
       // src/lexer.mll. Do not edit by hand.\n\n" ;
    output_string oc "export const abellaKeywords = {\n" ;
    List.iter (fun (field, cat) ->
        Printf.fprintf oc "  %s: [\n" field ;
        List.iter (fun word -> Printf.fprintf oc "    %S,\n" word)
          (words_of cat) ;
        output_string oc "  ],\n")
      groups ;
    output_string oc "} as const;\n\n" ;
    output_string oc "export const allAbellaKeywords = [\n" ;
    List.iter (fun word -> Printf.fprintf oc "  %S,\n" word) (all_words ()) ;
    output_string oc "] as const;\n"
  end

let main output_path =
  check_keywords () ;
  check_groups () ;
  output output_path

let () =
  let open Cmdliner in
  let output =
    let doc = "Output TypeScript module." in
    Arg.(required @@ opt (some string) None @@
         info ["o" ; "output"] ~doc ~docv:"FILE")
  in
  let cmd =
    let doc = "Generate the shared Abella keyword tables." in
    Cmd.v (Cmd.info "abella_keywords" ~doc)
      Term.(const main $ output)
  in
  exit (Cmd.eval cmd)
